package com.example.basics

fun main() {
    println("operadores aritmeticos")

    val precioboleto: Double = 250.0
    val impuestos: Double = 30.0

    println("total: ${precioboleto + impuestos}")
    println("resta: ${precioboleto - impuestos}")
    println("multiplicacion: ${precioboleto * 2}")
    println("division: ${precioboleto / 2}")
}

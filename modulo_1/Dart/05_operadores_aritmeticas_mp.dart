void main() {
  print("operaciones aritmeticas");

  final double tarifaBase = 12.5;
  final double cargosExtras = 5;

  print("suma $tarifaBase + $cargosExtras = ${tarifaBase + cargosExtras}");
  print("resta $tarifaBase - $cargosExtras = ${tarifaBase - cargosExtras}");
  print("multiplicacion $tarifaBase * $cargosExtras = ${tarifaBase * cargosExtras}");
  print("division $tarifaBase / $cargosExtras = ${tarifaBase / cargosExtras}");
}
